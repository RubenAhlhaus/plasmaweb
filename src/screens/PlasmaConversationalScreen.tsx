import { useEffect, useMemo, useRef, useState } from 'react';
import { useTranslation } from 'react-i18next';

import { TouchNumericPickerField } from '@/components/numeric';
import { ToolpathCanvas } from '@/components/plasma/ToolpathCanvas';
import { ToggleSwitch } from '@/components/ui/ToggleSwitch';
import { usePendingWsCommandResult } from '@/hooks/usePendingWsCommandResult';
import { usePlasmaCommands } from '@/hooks/usePlasmaCommands';
import { useAppStore } from '@/store';
import type { PlasmaToolpath } from '@/store/types';

type ShapeParameter = { name: string; required: boolean; default: unknown };
type ShapeSchemas = Record<string, ShapeParameter[]>;

/**
 * The machine fills these in from the material and the prefs, so the form leaves them out.
 * Sending them anyway would let a form quietly cut with a kerf the material does not have.
 */
const MACHINE_SUPPLIED = new Set([
  'matNumber',
  'matName',
  'preAmble',
  'postAmble',
  'kerfWidth',
  'leadinLength',
  'leadoutLength',
  'smallHoleDia',
  'smallHoleSpeed',
]);

/** Upstream's parameter names carry their own types; these are the ones that are not floats. */
const BOOLEAN_PARAMETERS = new Set([
  'isCenter',
  'isExternal',
  'isOvercut',
  'inStyle',
  'diaOrLen',
  'rButton',
]);
const INTEGER_PARAMETERS = new Set([
  'sides',
  'points',
  'holeNum',
  'invalidLeads',
  'smallHoleSpeed',
]);
/** Per-corner style/text on a rectangle: free text upstream, so free text here. */
const TEXT_PARAMETERS = new Set([
  'styleR1',
  'styleR2',
  'styleR3',
  'styleR4',
  'textR1',
  'textR2',
  'textR3',
  'textR4',
]);

const buttonClass =
  'rounded-md border border-white/10 bg-slate-900/60 px-4 py-2 text-sm font-semibold uppercase tracking-wide hover:border-white/25 disabled:opacity-40';

function initialValue(parameter: ShapeParameter): string | boolean {
  if (BOOLEAN_PARAMETERS.has(parameter.name)) {
    return parameter.default === true;
  }
  if (TEXT_PARAMETERS.has(parameter.name)) {
    return parameter.default === undefined || parameter.default === null
      ? ''
      : String(parameter.default);
  }
  return parameter.default === undefined || parameter.default === null
    ? '0'
    : String(parameter.default);
}

/**
 * QtPlasmaC's CONVERSATIONAL tab: shapes generated by LinuxCNC's own `plasmac` modules.
 *
 * The forms are built from the schema the backend read off those modules, so this screen has no
 * second copy of what a shape needs — a LinuxCNC with a different parameter list renders a
 * different form rather than silently dropping a field.
 *
 * ADD keeps the generated job and clears the canvas for the next shape; SAVE writes the job into
 * the machine's program directory and loads it, which is when it becomes something to cut.
 */
export function PlasmaConversationalScreen() {
  const { t } = useTranslation('plasma');
  const commands = usePlasmaCommands();

  const [schemas, setSchemas] = useState<ShapeSchemas | null>(null);
  const [shape, setShape] = useState<string | null>(null);
  const [values, setValues] = useState<Record<string, string | boolean>>({});
  const [job, setJob] = useState<string | null>(null);
  const [preview, setPreview] = useState<PlasmaToolpath | null>(null);
  const [message, setMessage] = useState<string | null>(null);

  // The last generated job is state rather than a ref: ADD is disabled until there is one, and
  // a ref would leave that button stale until some other render happened to come along.
  const [generated, setGenerated] = useState<string | null>(null);

  const shapesRef = useRef<string | null>(null);
  const generateRef = useRef<string | null>(null);
  const previewRef = useRef<string | null>(null);

  const available = useAppStore((s) => s.plasmaAvailable);

  // Ask once per connection: the shape list is a property of the installed LinuxCNC.
  useEffect(() => {
    if (!available || schemas) return;
    const commandId = commands.conversationalShapes();
    if (commandId) shapesRef.current = commandId;
  }, [available, commands, schemas]);

  usePendingWsCommandResult(shapesRef, {
    onResult: (result) => {
      shapesRef.current = null;
      if (!result.ok || !result.result) {
        setMessage(result.error?.message ?? t('conversational.unavailable'));
        return;
      }
      const payload = (result.result as { shapes?: ShapeSchemas }).shapes ?? {};
      setSchemas(payload);
      const first = Object.keys(payload)[0];
      if (first) selectShape(first, payload);
    },
  });

  usePendingWsCommandResult(generateRef, {
    onResult: (result) => {
      generateRef.current = null;
      if (!result.ok) {
        setMessage(result.error?.message ?? t('conversational.failed'));
        return;
      }
      const payload = result.result as { gcode?: string | null; error?: string | null; path?: string };
      if (payload.error) {
        setMessage(payload.error);
        return;
      }
      setGenerated(payload.gcode ?? null);
      setMessage(payload.path ? t('conversational.saved', { path: payload.path }) : null);
      if (payload.gcode) {
        const commandId = commands.toolpathFromGcode(payload.gcode);
        if (commandId) previewRef.current = commandId;
      }
    },
  });

  usePendingWsCommandResult(previewRef, {
    onResult: (result) => {
      previewRef.current = null;
      if (result.ok && result.result) {
        setPreview(result.result as unknown as PlasmaToolpath);
        return;
      }
      setMessage(result.error?.message ?? t('conversational.previewFailed'));
    },
  });

  const selectShape = (name: string, from?: ShapeSchemas) => {
    const schema = (from ?? schemas)?.[name] ?? [];
    setShape(name);
    setValues(
      Object.fromEntries(
        schema
          .filter((parameter) => !MACHINE_SUPPLIED.has(parameter.name))
          .map((parameter) => [parameter.name, initialValue(parameter)]),
      ),
    );
    setPreview(null);
    setGenerated(null);
    setMessage(null);
  };

  const fields = useMemo(
    () => (shape && schemas ? schemas[shape].filter((p) => !MACHINE_SUPPLIED.has(p.name)) : []),
    [shape, schemas],
  );

  const send = (save: boolean) => {
    if (!shape) return;
    const params: Record<string, unknown> = {};
    for (const [name, value] of Object.entries(values)) {
      if (typeof value === 'boolean' || TEXT_PARAMETERS.has(name)) {
        params[name] = value;
        continue;
      }
      const parsed = Number(value);
      params[name] = Number.isFinite(parsed) ? parsed : value;
    }
    const commandId = commands.conversational({ shape, params, job: job ?? undefined, save });
    if (commandId) {
      generateRef.current = commandId;
      setMessage(null);
    }
  };

  if (!schemas) {
    return (
      <div
        className="flex h-full items-center justify-center text-sm text-muted-foreground"
        data-e2e="plasma-conversational-loading"
      >
        {message ?? t('conversational.loading')}
      </div>
    );
  }

  return (
    <div
      className="grid h-full min-h-0 gap-4 lg:grid-cols-[22rem_minmax(0,1fr)]"
      data-e2e="plasma-conversational"
    >
      <div className="flex min-h-0 flex-col gap-3 overflow-y-auto">
        <div className="flex flex-wrap gap-1" data-e2e="plasma-conversational-shapes">
          {Object.keys(schemas).map((name) => (
            <button
              key={name}
              type="button"
              data-e2e={`plasma-conversational-shape-${name}`}
              className={`rounded-md px-3 py-2 text-xs font-semibold uppercase tracking-wide ${
                shape === name
                  ? 'bg-slate-800/90 text-foreground'
                  : 'text-muted-foreground hover:bg-slate-900/60'
              }`}
              onClick={() => selectShape(name)}
            >
              {t(`conversational.shape.${name}`, { defaultValue: name.replace('_', ' ') })}
            </button>
          ))}
        </div>

        <div className="grid gap-3 sm:grid-cols-2">
          {fields.map((parameter) =>
            BOOLEAN_PARAMETERS.has(parameter.name) ? (
              <div key={parameter.name} className="flex items-center justify-between gap-2">
                <span className="text-sm text-muted-foreground">
                  {t(`conversational.field.${parameter.name}`, { defaultValue: parameter.name })}
                </span>
                <ToggleSwitch
                  checked={values[parameter.name] === true}
                  onCheckedChange={() =>
                    setValues((prev) => ({
                      ...prev,
                      [parameter.name]: prev[parameter.name] !== true,
                    }))
                  }
                  data-e2e={`plasma-conversational-${parameter.name}`}
                />
              </div>
            ) : (
              <TouchNumericPickerField
                key={parameter.name}
                label={t(`conversational.field.${parameter.name}`, { defaultValue: parameter.name })}
                value={String(values[parameter.name] ?? '')}
                integerOnly={INTEGER_PARAMETERS.has(parameter.name)}
                onChange={(next) => setValues((prev) => ({ ...prev, [parameter.name]: next }))}
                data-e2e={`plasma-conversational-${parameter.name}`}
              />
            ),
          )}
        </div>

        <div className="flex flex-wrap gap-2">
          <button
            type="button"
            className={buttonClass}
            data-e2e="plasma-conversational-preview"
            onClick={() => send(false)}
          >
            {t('conversational.preview')}
          </button>
          <button
            type="button"
            className={buttonClass}
            data-e2e="plasma-conversational-add"
            disabled={!generated}
            onClick={() => {
              setJob(generated);
              setMessage(t('conversational.added'));
            }}
          >
            {t('conversational.add')}
          </button>
          <button
            type="button"
            className={buttonClass}
            data-e2e="plasma-conversational-save"
            onClick={() => send(true)}
          >
            {t('conversational.save')}
          </button>
          <button
            type="button"
            className={buttonClass}
            data-e2e="plasma-conversational-clear"
            disabled={!job}
            onClick={() => {
              setJob(null);
              setPreview(null);
              setMessage(t('conversational.cleared'));
            }}
          >
            {t('conversational.clear')}
          </button>
        </div>

        {message && (
          <div className="text-sm text-amber-300" data-e2e="plasma-conversational-message">
            {message}
          </div>
        )}
        {job && (
          <div className="text-xs text-muted-foreground" data-e2e="plasma-conversational-job">
            {t('conversational.jobLines', { count: job.split('\n').length })}
          </div>
        )}
      </div>

      <div className="min-h-0 rounded-md border border-white/10 bg-slate-950/40">
        {preview ? (
          <ToolpathCanvas toolpath={preview} />
        ) : (
          <div
            className="flex h-full items-center justify-center px-6 text-center text-sm text-muted-foreground"
            data-e2e="plasma-conversational-empty"
          >
            {t('conversational.previewHint')}
          </div>
        )}
      </div>
    </div>
  );
}
